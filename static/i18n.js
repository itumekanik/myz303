"use strict";
/*
 * Language support (Turkish / English). Loaded before app.js.
 *
 * - Static page text: elements carry data-i18n="key"; their Turkish content stays in
 *   index.html and the English version lives in STATIC_EN[key] (author-written HTML).
 *   data-i18n-attr="title=key,aria-label=key" translates attributes the same way.
 * - Text built by the scripts: t("key", { name: value }) looks up STRINGS[key] = { tr, en };
 *   L({ tr, en }) picks the current language from an inline pair.
 * - Changing the language fires a "lang-change" event so every view can re-render.
 */
const I18N = { lang: "tr" };
try {
  const saved = localStorage.getItem("lang");
  if (saved === "tr" || saved === "en") I18N.lang = saved;
} catch { /* storage blocked: Turkish */ }
document.documentElement.lang = I18N.lang;

/** Picks the current language from a { tr, en } pair; anything else passes through. */
function L(value) {
  if (value && typeof value === "object" && !Array.isArray(value) && ("tr" in value || "en" in value)) {
    return value[I18N.lang] ?? value.tr;
  }
  return value;
}

/** A UI string by key, with {placeholders} filled from params. */
function t(key, params) {
  const entry = STRINGS[key];
  let text = entry ? (entry[I18N.lang] ?? entry.tr) : key;
  if (params) text = text.replace(/\{(\w+)\}/g, (_, name) => (params[name] ?? ""));
  return text;
}

/** Swaps the static page text (index.html) to the current language. */
function applyStaticTranslations() {
  for (const el of document.querySelectorAll("[data-i18n]")) {
    if (el._tr === undefined) el._tr = el.innerHTML;          // the Turkish original
    const en = STATIC_EN[el.dataset.i18n];
    el.innerHTML = I18N.lang === "en" && en !== undefined ? en : el._tr;
  }
  for (const el of document.querySelectorAll("[data-i18n-attr]")) {
    el._trAttr ??= {};
    for (const pair of el.dataset.i18nAttr.split(",")) {
      const [attr, key] = pair.split("=").map((s) => s.trim());
      if (!(attr in el._trAttr)) el._trAttr[attr] = el.getAttribute(attr) ?? "";
      const en = STATIC_EN[key];
      el.setAttribute(attr, I18N.lang === "en" && en !== undefined ? en : el._trAttr[attr]);
    }
  }
  document.title = I18N.lang === "en" ? "SimpleCNN Dashboard" : "SimpleCNN Paneli";
  for (const b of document.querySelectorAll("#lang-switch button")) {
    b.setAttribute("aria-pressed", String(b.dataset.lang === I18N.lang));
  }
}

function setLang(lang) {
  if (lang === I18N.lang) return;
  I18N.lang = lang;
  document.documentElement.lang = lang;
  try { localStorage.setItem("lang", lang); } catch { /* not saved */ }
  applyStaticTranslations();
  document.dispatchEvent(new CustomEvent("lang-change", { detail: lang }));
}

