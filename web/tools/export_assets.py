"""
Exports what the CNN chapter of the static site needs from the Python side, as JavaScript data
files that a page can load with a <script> tag (which also works when the page is opened from a
file, where fetch() is not allowed).

    .venv/Scripts/python.exe web/tools/export_assets.py      (from the repository root)

Reads checkpoints/simple_cnn.pt, checkpoints/simple_cnn_run.json and data/MNIST/raw (created by
`python dashboard.py` or `python SimpleCNN.py`) and writes web/public/data/:

    cnn-trained.js   the trained SimpleCNN weights (float32) and the run's settings and results
    cnn-initial.js   the random weights that run started from (the "before training" model)
    cnn-run.js       the run itself (curves, filters, sample predictions, log) for the Training tab
    mnist-test.js    the 10,000 test images and labels (the original .gz files)
    mnist-train.js   the 60,000 training images and labels, and which 12,000 are the validation set
                     (the same split as SimpleCNN.py with the run's seed)

and web/tests/fixtures/cnn-parity.json: PyTorch's outputs on a few test images, which the unit
tests compare with the JavaScript forward pass.

Each data file runs `(window.__AI_DATA__ ||= {})[name] = {...}`; binary arrays are base64 strings,
gzip-compressed where that helps ({"gzip": ...}).
"""
import base64
import gzip
import json
import sys
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F
from torch.utils.data import random_split

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
import SimpleCNN as cnn  # noqa: E402

OUT = ROOT / "web" / "public" / "data"
FIXTURES = ROOT / "web" / "tests" / "fixtures"
RAW = ROOT / "data" / "MNIST" / "raw"


def b64(array: np.ndarray) -> str:
    return base64.b64encode(np.ascontiguousarray(array).tobytes()).decode("ascii")


def tensors(state_dict: dict) -> dict:
    """Float tensors as {name: {shape, data}} (data: base64 of little-endian float32, PyTorch layout)."""
    return {name: {"shape": list(t.shape), "data": b64(t.detach().cpu().numpy().astype("<f4"))}
            for name, t in state_dict.items() if t.dtype.is_floating_point}


def write(name: str, payload: dict) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    text = (f"/* Generated by web/tools/export_assets.py. Do not edit. */\n"
            f"(window.__AI_DATA__ ||= {{}})[{json.dumps(name)}] = {json.dumps(payload, separators=(',', ':'))};\n")
    path = OUT / f"{name}.js"
    path.write_text(text, encoding="utf-8")
    print(f"  {path.relative_to(ROOT).as_posix():40} {path.stat().st_size / 1e6:6.2f} MB")


def gz_file(name: str) -> dict:
    """An original MNIST .gz file, as it is (the browser unpacks it with DecompressionStream)."""
    return {"gzip": base64.b64encode((RAW / name).read_bytes()).decode("ascii")}


def main() -> None:
    checkpoint = torch.load(ROOT / "checkpoints" / "simple_cnn.pt", map_location="cpu", weights_only=True)
    run = json.loads((ROOT / "checkpoints" / "simple_cnn_run.json").read_text(encoding="utf-8"))
    meta = checkpoint.get("meta") or {}
    if run.get("trained_at") != meta.get("trained_at"):
        raise SystemExit("simple_cnn_run.json belongs to another run than simple_cnn.pt")
    seed = meta.get("seed", cnn.seed)
    print(f"Run of {meta.get('trained_at')}: test accuracy {meta.get('test_acc')}%, seed {seed}")

    # The validation split: the same calls in the same order as SimpleCNN.py's main (and the
    # dashboard), so the global random generator is in the same state when random_split runs
    cnn.set_seed(seed)
    cnn._setup_model_for_training(cnn.num_class, meta.get("lr", cnn.learning_rate))
    _train, val = random_split(range(60000), [1 - cnn.validation_split, cnn.validation_split])
    val_indices = np.array(list(val), dtype="<u2")
    train_labels = np.frombuffer(gzip.decompress((RAW / "train-labels-idx1-ubyte.gz").read_bytes()), np.uint8, offset=8)
    first = [int(train_labels[i]) for i in val_indices[:len(run["samples"]["labels"])]]
    if first != run["samples"]["labels"]:
        raise SystemExit("The reproduced validation split does not match the run's sample images")
    print(f"Validation split reproduced: {len(val_indices)} images (the run's {len(first)} samples match)")

    trained = {k: v for k, v in checkpoint["state_dict"].items()}
    write("cnn-trained", {"meta": meta, "tensors": tensors(trained)})
    write("cnn-initial", {"seed": seed, "tensors": tensors(checkpoint["initial_state_dict"])})
    write("cnn-run", run)
    write("mnist-test", {"images": gz_file("t10k-images-idx3-ubyte.gz"), "labels": gz_file("t10k-labels-idx1-ubyte.gz")})
    write("mnist-train", {"images": gz_file("train-images-idx3-ubyte.gz"), "labels": gz_file("train-labels-idx1-ubyte.gz"),
                          "validation": {"gzip": base64.b64encode(gzip.compress(val_indices.tobytes())).decode("ascii")}})

    # Parity fixture: PyTorch's outputs for the first test images, every stage the page shows
    model = cnn.SimpleCNN(num_classes=cnn.num_class)
    model.load_state_dict(trained)
    model.eval()
    images = np.frombuffer(gzip.decompress((RAW / "t10k-images-idx3-ubyte.gz").read_bytes()), np.uint8, offset=16)
    n = 8
    x = torch.from_numpy(images[:n * 784].astype(np.float32) / 255).view(n, 1, 28, 28)
    with torch.no_grad():
        c1 = F.relu(model.batch1(model.conv1(x)))
        p1 = model.max1(c1)
        c2 = F.relu(model.batch2(model.conv2(p1)))
        p2 = model.max2(c2)
        f1 = F.relu(model.fc1(torch.flatten(p2, 1)))
        logits = model.fc2(f1)
    FIXTURES.mkdir(parents=True, exist_ok=True)
    fixture = {
        "images": b64(images[:n * 784]),
        "logits": logits.numpy().round(5).tolist(),
        "sums": {name: t.flatten(1).sum(1).numpy().round(4).tolist()
                 for name, t in {"conv1": c1, "pool1": p1, "conv2": c2, "pool2": p2, "fc1": f1}.items()},
    }
    (FIXTURES / "cnn-parity.json").write_text(json.dumps(fixture), encoding="utf-8")
    print(f"  {(FIXTURES / 'cnn-parity.json').relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
